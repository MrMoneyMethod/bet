#!/usr/bin/env python3
"""Embed local browser assets. Build-time only; no Python runtime dependency."""
import argparse
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
parser.add_argument("--output", type=Path, required=True)
args = parser.parse_args()
assets = {"index_html": "index.html", "styles_css": "styles.css", "app_js": "app.js", "favicon_svg": "favicon.svg"}
lines = ["// Generated by scripts/embed_assets.py. Do not edit.", "#pragma once", "namespace edgecourt::assets {"]
for i, (symbol, filename) in enumerate(assets.items()):
    content = (args.root / "web" / filename).read_text(encoding="utf-8")
    delimiter = f"EC_ASSET_{i}"
    if f'){delimiter}\"' in content:
        raise ValueError("Raw-string delimiter collision")
    lines.append(f'inline constexpr char {symbol}[] = R"{delimiter}({content}){delimiter}";')
lines.append("} // namespace edgecourt::assets\n")
args.output.parent.mkdir(parents=True, exist_ok=True)
args.output.write_text("\n".join(lines), encoding="utf-8")
